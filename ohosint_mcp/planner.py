"""Deterministic investigation planning.

``build_plan`` turns a target (and its detected type) into a detailed,
phase-by-phase OSINT plan that names the exact MCP tool to call at each step,
why the step is passive, and what to look for. It is pure (no network, no
mutation) so it can be unit-tested and reused by the orchestrator tools.

The plan is deliberately *not* generated by an LLM — it is a fixed, reviewed
procedure so the same target always yields the same auditable steps. The LLM
client's job is to execute the plan via the granular tools and to react to
what comes back (the pivot loop).
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

TARGET_TYPES = ("email", "phone", "name", "username", "domain")

_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
_PHONE_RE = re.compile(r"^\+?[0-9][0-9\s().-]{6,}$")

# Tool names referenced by the plan (kept as literals so the plan text always
# matches the registered MCP tool names).
TOOLS = {
    "configure": "configure",
    "status": "status",
    "tor_check": "tor_check",
    "rotate": "rotate_tor_circuit",
    "plan": "osint_plan",
    "run": "run_investigation",
    "email": "investigate_email",
    "phone": "investigate_phone",
    "name": "investigate_name",
    "candidates": "generate_candidates",
    "sweep": "sweep_username",
    "breach": "breach_search",
    "subdomains": "enumerate_subdomains",
    "docs": "hunt_docs",
    "onion": "search_onion",
    "github": "github_leaks",
    "dork": "search_dork",
    "suggest": "suggest",
    "mentions": "mentions",
    "autopsy": "autopsy_url",
    "autodork": "auto_dork_url",
    "pivot": "pivot_results",
    "clear": "clear_session",
}

HARD_RULES = [
    "GET-only against public pages and third-party APIs; never POST to login, "
    "recovery, forgot-password, or OTP endpoints (those notify the target).",
    "No account creation, no login attempts, no use of credentials found in "
    "breach data.",
    "Randomized inter-request delays and User-Agent rotation are always on.",
    "Route through Tor (configure proxy=socks5h://127.0.0.1:9050) to hide the "
    "origin IP; use socks5h:// not socks5:// to avoid DNS leaks.",
    "Lawful purpose required: authorized assessment, your own accounts, or an "
    "active legal case.",
]


def detect_target_type(target: str) -> str:
    """Best-effort target-type detection: email > phone > domain > name > username."""
    t = (target or "").strip()
    if not t:
        raise ValueError("empty target")
    if _EMAIL_RE.match(t):
        return "email"
    if _PHONE_RE.match(t):
        digits = re.sub(r"\D", "", t)
        if len(digits) >= 7:
            return "phone"
    if re.match(r"^(?=.{1,253}$)([a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?\.)+[a-zA-Z]{2,63}$", t):
        return "domain"
    if " " in t:
        return "name"
    return "username"


def _step(tool: str, args: Dict[str, Any], why: str, watch_for: str) -> Dict[str, Any]:
    return {"tool": tool, "args": args, "why": why, "watch_for": watch_for}


def _phase(index: int, name: str, goal: str, steps: List[Dict[str, Any]]) -> Dict[str, Any]:
    return {"phase": index, "name": name, "goal": goal, "steps": steps}


def _opsec_phase() -> Dict[str, Any]:
    return _phase(
        0,
        "OPSEC setup",
        "Hide the origin IP and throttle politely before any query leaves the machine.",
        [
            _step(
                TOOLS["configure"],
                {"proxy": "socks5h://127.0.0.1:9050", "delay_min": 1.5, "delay_max": 3.5},
                "Tunnel every request through Tor; socks5h routes DNS through Tor too.",
                "Confirm tor is up, otherwise requests will fail fast.",
            ),
            _step(
                TOOLS["tor_check"],
                {},
                "Verify the exit IP is actually a Tor relay before touching any source.",
                "A non-Tor IP means the proxy is not working; fix before proceeding.",
            ),
        ],
    )


def _email_phases(target: str) -> List[Dict[str, Any]]:
    return [
        _phase(
            1,
            "Normalize + candidate generation",
            "Turn the email into the identity fragments the rest of the plan pivots on.",
            [
                _step(
                    TOOLS["email"],
                    {"address": target, "sweep_candidates": False},
                    "Breach metadata (LeakCheck / Hudson Rock), Gravatar profile, and "
                    "username candidates — all against third-party DBs, never the target.",
                    "Linked Gravatar accounts and candidate handles are the highest-value pivots.",
                ),
                _step(
                    TOOLS["candidates"],
                    {"seed": target, "year": None},
                    "Enumerate handle permutations (separators, name swap, year hints) locally.",
                    "Short, clean candidates are the sweep list for the next phase.",
                ),
            ],
        ),
        _phase(
            2,
            "Breach & leak triage",
            "Establish what is already publicly exposed about the address.",
            [
                _step(
                    TOOLS["breach"],
                    {"query": target, "type": "email"},
                    "Multi-source breach lookup (LeakCheck, HIBP catalogue, XposedOrNot, "
                    "ProxyNova, EmailRep, …) — keyless by default.",
                    "Breach names that mention adult platforms imply combo lists that may "
                    "contain the handle itself.",
                ),
                _step(
                    TOOLS["github"],
                    {"query": target},
                    "Search public code/commits/users for the email (code search needs OHO_GITHUB_KEY).",
                    "Commit messages and .env dumps frequently contain emails.",
                ),
            ],
        ),
        _phase(
            3,
            "Handle sweep",
            "Find which sites the target's likely usernames are registered on.",
            [
                _step(
                    TOOLS["sweep"],
                    {"username": "<candidate>", "nsfw": False},
                    "GET-probe each candidate across the Maigret/Sherlock site DB (needs "
                    "`pip install maigret sherlock-project`).",
                    "confirmed/claimed hits become autopsy + pivot sources.",
                ),
                _step(
                    TOOLS["suggest"],
                    {"query": "<candidate>"},
                    "Autocomplete pivots reveal what the world searches around the handle.",
                    "New name/handle fragments to fold back into candidate generation.",
                ),
                _step(
                    TOOLS["mentions"],
                    {"query": target},
                    "Who is talking about this identifier (Reddit / StackExchange).",
                    "Authors and quoted text that mention the target.",
                ),
            ],
        ),
        _phase(
            4,
            "Pivot, correlate, conclude",
            "Loop harvested handles back into the sweep until no new identifiers appear.",
            [
                _step(
                    TOOLS["autopsy"],
                    {"url": "<confirmed-profile-url>"},
                    "Harvest cross-platform links, emails and @handles from a confirmed profile.",
                    "New usernames/emails to feed back into earlier phases.",
                ),
                _step(
                    TOOLS["autodork"],
                    {"url": "<confirmed-profile-url>", "anchors": None},
                    "Extract distinctive keywords and build anchor-aware dorks.",
                    "Bio keywords + anchor combinations that surface other accounts.",
                ),
                _step(
                    TOOLS["pivot"],
                    {},
                    "Correlate collected results into ranked new usernames and emails.",
                    "Re-run phases 1-3 for each new pivot until the graph stabilizes.",
                ),
            ],
        ),
    ]


def _phone_phases(target: str) -> List[Dict[str, Any]]:
    return [
        _phase(
            1,
            "Normalize + dork every format",
            "Reduce the number to its canonical forms and hunt them passively.",
            [
                _step(
                    TOOLS["phone"],
                    {"number": target},
                    "E.164/national/international normalization, line type, carrier, and "
                    "ready-made dorks — all local math.",
                    "Every formatting of the number is a search pivot.",
                ),
                _step(
                    TOOLS["dork"],
                    {"query": "\"<e164-or-national>\""},
                    "Search-engine dorks for each number format (DDG + Bing, Google if keyed).",
                    "Directory, forum, and leak pages quoting the number.",
                ),
                _step(
                    TOOLS["mentions"],
                    {"query": target},
                    "Reddit / StackExchange mentions of the number.",
                    "Posts that name the number's owner.",
                ),
            ],
        ),
        _phase(
            2,
            "Pivot & conclude",
            "Phone is a weak standalone identifier; pivot to name/email and repeat.",
            [
                _step(
                    TOOLS["plan"],
                    {"target": "<name-or-email-found>", "target_type": None},
                    "Re-plan around any name/email the dorks surfaced.",
                    "A phone-only investigation should terminate here otherwise.",
                ),
            ],
        ),
    ]


