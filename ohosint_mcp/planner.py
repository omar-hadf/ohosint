def _domain_phases(target: str) -> List[Dict[str, Any]]:
    return [
        _phase(
            1,
            "Map the attack surface (passively)",
            "Enumerate subdomains and exposed files without touching the target's infra.",
            [
                _step(TOOLS["subdomains"], {"domain": target},
                      "crt.sh / HackerTarget / OTX passive subdomain enum (no brute force).",
                      "Subdomains to inspect and to feed docs/dork hunts."),
                _step(TOOLS["docs"], {"target": target},
                      "filetype:/open-dir/cloud-bucket dork pack for exposed documents.",
                      "Exposed PDFs, backups, configs, and buckets."),
                _step(TOOLS["breach"], {"query": target, "type": "domain"},
                      "Breach lookup scoped to the whole domain.",
                      "Employee emails and credential leaks affecting the domain."),
            ],
        ),
        _phase(
            2,
            "Expand & conclude",
            "Follow the domain to its operators.",
            [
                _step(TOOLS["dork"], {"query": "site:<domain> \"contact\" OR \"@domain\""},
                      "Dorks for contact pages and staff emails.", "People to investigate."),
                _step(TOOLS["onion"], {"query": target},
                      "Ahmia dark-web mention search (open results with Tor).",
                      "Dark-web references to the domain."),
            ],
        ),
    ]


_PHASE_BUILDERS = {
    "email": _email_phases,
    "phone": _phone_phases,
    "name": _name_phases,
    "username": _username_phases,
    "domain": _domain_phases,
}

_SKILLS = {
    "email": ["silent-recon"],
    "phone": ["silent-recon"],
    "name": ["silent-recon"],
    "username": ["silent-recon"],
    "domain": ["silent-recon"],
}


def build_plan(target: str, target_type: Optional[str] = None) -> Dict[str, Any]:
    """Build a detailed, phased investigation plan for ``target``.

    Returns a dict with ``phases`` (structured), ``skills``, ``hard_rules`` and
    a human-readable ``plan_text`` markdown rendering.
    """
    target = (target or "").strip()
    if not target:
        raise ValueError("empty target")
    if target_type is None:
        target_type = detect_target_type(target)
    target_type = target_type.lower()
    if target_type not in TARGET_TYPES:
        raise ValueError(
            f"unknown target_type {target_type!r}; expected one of {TARGET_TYPES}"
        )

    phases = [_opsec_phase()] + _PHASE_BUILDERS[target_type](target)
    plan = {
        "target": target,
        "target_type": target_type,
        "hard_rules": HARD_RULES,
        "skills": _SKILLS[target_type],
        "phases": phases,
    }
    plan["plan_text"] = _render_plan(plan)
    return plan


def _render_plan(plan: Dict[str, Any]) -> str:
    lines: List[str] = []
    lines.append(f"# OSINT plan — {plan['target']} ({plan['target_type']})")
    lines.append("")
    lines.append("## Hard rules")
    for rule in plan["hard_rules"]:
        lines.append(f"- {rule}")
    lines.append("")
    lines.append("## Skills to consult")
    for skill in plan["skills"]:
        lines.append(f"- resource `skills://{skill}`")
    lines.append("")
    for phase in plan["phases"]:
        lines.append(f"## Phase {phase['phase']} — {phase['name']}")
        lines.append(f"*{phase['goal']}*")
        for step in phase["steps"]:
            lines.append(f"- **{step['tool']}** `{step['args']}`")
            lines.append(f"  - why: {step['why']}")
            lines.append(f"  - watch for: {step['watch_for']}")
        lines.append("")
    lines.append("Loop the pivot phase until new identifiers stop appearing, then "
                 "conclude and save a report.")
    return "\n".join(lines)
